/* Regenerates the worked-case table in docs/UNDERSTANDING-SCORE-CASES.md under
   METRICS rev 8.1 and asserts the doc-level orderings. The section between the
   markers is rewritten only when its content changed. */
import { describe, it, expect } from 'vitest'
import { readFileSync, writeFileSync } from 'fs'
import { resolve } from 'path'
import { CASES, renderCaseTable, scoreCase } from './cases'

const DOC = resolve(__dirname, '../../../docs/UNDERSTANDING-SCORE-CASES.md')
const BEGIN = '<!-- BEGIN generated: scoring cases rev 4 -->'
const END = '<!-- END generated: scoring cases rev 4 -->'

const HEADER = `## Rev 4 — values under METRICS rev 8.1 (generated by tests)
*Generated by \`src/lib/scoring/cases.test.ts\` from the fixtures in \`src/lib/scoring/cases.ts\`; do not edit by hand — run \`pnpm test\`. Rules: Recognized = Σw·id/Σw; Invented = Σw_inv/Σw; Net = (Σw·id − Σp·w_inv)/Σw floored at 0 with p = 1 core/secondary, 0.5 garnish/spice; Quantity = Σg·grade/(Σg + Σe_inv), grade = min/max, missed and wrong = 0, substitutes graded normally, truth items without grams excluded; wrong pairing = missed + invented (pred grams in the denominator, tag from the paired truth item); drinks dropped; ignore dropped on both sides. F1 on exact rows only (substitute = FP + FN, many-to-one counted once). Mass MAE / MSA / SSPB over matched units whose truth items are all basis = weighed. No combined score exists any more — Net and Quantity are read as two numbers.*
`

describe('worked cases — orderings claimed by UNDERSTANDING-SCORE-CASES.md', () => {
  const r = Object.fromEntries(CASES.map((c) => [c.n, scoreCase(c)]))
  it('1 baseline sits between 3 (protein missed) and 2 (context) on both axes', () => {
    expect(r[3].net).toBeLessThan(r[1].net)
    expect(r[1].net).toBeLessThan(r[2].net)
    expect(r[3].quantity).toBeLessThan(r[1].quantity)
    expect(r[1].quantity).toBeLessThan(r[2].quantity)
  })
  it('5 (wrong, confident) < 3 (missed) < 1', () => {
    expect(r[5].net).toBeLessThan(r[3].net)
    expect(r[5].quantity).toBeLessThan(r[3].quantity)
  })
  it('4 (substitute) costs Recognized only', () => {
    expect(r[4].recognized).toBeLessThan(r[2].recognized)
    expect(r[4].quantity).toBeCloseTo(r[2].quantity, 12)
  })
  it('6 (padded) stays above 1 on Net and Quantity', () => {
    expect(r[6].net).toBeGreaterThan(r[1].net)
    expect(r[6].quantity).toBeGreaterThan(r[1].quantity)
  })
  it('8 (context only) ≈ 2', () => {
    expect(Math.abs(r[8].net - r[2].net)).toBeLessThan(0.05)
  })
})

describe('doc regeneration', () => {
  it('writes the Rev 4 section into docs/UNDERSTANDING-SCORE-CASES.md (idempotent)', () => {
    const table = renderCaseTable()
    expect(table).toContain('| 1 | phone, image only |')
    const block = `${BEGIN}\n${HEADER}\n${table}\n${END}`
    const before = readFileSync(DOC, 'utf8')
    let after: string
    const b = before.indexOf(BEGIN)
    const e = before.indexOf(END)
    if (b >= 0 && e > b) {
      after = before.slice(0, b) + block + before.slice(e + END.length)
    } else {
      after = before.replace(/\s*$/, '') + '\n\n' + block + '\n'
    }
    if (after !== before) writeFileSync(DOC, after)
    const now = readFileSync(DOC, 'utf8')
    expect(now).toContain(BEGIN)
    expect(now).toContain(table)
    expect(now.indexOf(BEGIN)).toBe(now.lastIndexOf(BEGIN))
  })
})
